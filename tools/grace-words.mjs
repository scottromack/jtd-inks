// Generates assets/js/grace-words.js from GRACE-lang.md: the GRACE highlighter's word
// lists, never hand-written (the same `Term <name>:` declarations check.py derives its
// reserved tokens from). Usage: node tools/grace-words.mjs [path/to/GRACE-lang.md]
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2] || "../grace-commons/GRACE-lang.md";
const g = readFileSync(src, "utf8");
const caps = (s) => [...new Set(s.match(/\b[A-Z]{2,}\b/g) || [])];
const term = (name) => {
  const m = g.match(new RegExp("^Term " + name.replace(/ /g, " ") + ":(.*)$", "m"));
  if (!m) throw new Error(`GRACE-lang.md has no "Term ${name}:" line`);
  return caps(m[1]);
};

const modal = term("modal").filter((w) => w !== "NOT"); // MUST, MAY; NOT joins as MUST NOT
const surface = term("surface");
const reserved = new Set();
for (const n of ["reserved token", "quantifier", "condition operator", "tail",
                 "reserved grammar verbs", "value sets"]) term(n).forEach((w) => reserved.add(w));
modal.forEach((w) => reserved.delete(w));
surface.forEach((w) => reserved.delete(w));

const words = { modal, surface, reserved: [...reserved].sort() };
writeFileSync("assets/js/grace-words.js",
  "// @generated by tools/grace-words.mjs from GRACE-lang.md. DO NOT EDIT.\n" +
  "window.GRACE_WORDS = " + JSON.stringify(words, null, 2) + ";\n");
console.log("grace-words:", words.modal.length, "modal,", words.surface.length, "surface,",
  words.reserved.length, "reserved");
